// Regenerates server/src/migrations-data.ts from the drizzle/*.sql files.
//
// Why this exists: the local standalone server can read the drizzle/
// folder from disk, but a Vercel Function's filesystem only contains
// files its bundler traced — a runtime readFile of drizzle/*.sql is
// not guaranteed to survive packaging. Embedding the SQL as a TS
// module makes the schema setup identical (and traceable) everywhere.
//
// The drizzle/ folder remains the source of truth. If you add or edit
// a migration, re-run:  bun run embed:migrations
// A byte-for-byte guard in server/src/host.ts is unnecessary because
// the embedded runner is idempotent (each file is recorded once
// applied, and DDL "already exists" errors are tolerated).

import { readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const DRIZZLE_DIR = join(ROOT, "drizzle");
const OUT = join(ROOT, "server", "src", "migrations-data.ts");

const files = (await readdir(DRIZZLE_DIR))
  .filter((f) => f.endsWith(".sql"))
  .sort(); // 0001_… … 0014_… — lexicographic order is apply order

const entries = [];
for (const name of files) {
  const sql = await readFile(join(DRIZZLE_DIR, name), "utf8");
  entries.push({ name, sql });
}

const body = `/* GENERATED by scripts/embed-migrations.mjs from drizzle/*.sql.
   Do not edit by hand — edit the .sql files and re-run
   \`bun run embed:migrations\`. */

export interface EmbeddedMigration {
  name: string;
  sql: string;
}

export const MIGRATIONS: EmbeddedMigration[] = ${JSON.stringify(entries, null, 2)};
`;

await writeFile(OUT, body);
console.log(`Embedded ${entries.length} migrations → ${OUT}`);
